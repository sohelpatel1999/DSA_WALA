// Node me planner ke items + lessons load karo (build.js / validate-lessons.js dono use karte hain)
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');            // dsa-visual/planner
const LESSON_DIR = path.join(ROOT, 'lessons');

function plannerItems() {
  const html = fs.readFileSync(path.join(ROOT, 'switch-prep-planner.html'), 'utf8');
  const a = html.indexOf('const LC = s =>'), b = html.indexOf('const TIER_RANK');
  if (a < 0 || b < 0) throw new Error('switch-prep-planner.html me DSA / TH list nahi mili');
  const fn = new Function(html.slice(a, b) + '\nreturn { DSA, TH };');
  const { DSA, TH } = fn();
  return DSA.concat(TH);
}

function lessonFiles() {
  return fs.readdirSync(LESSON_DIR).filter(f => f.endsWith('.js') && f !== 'manifest.js').sort();
}

// visualizers.js + lesson-kit.js + har lesson file; return { lessons: {id: L}, fileOf: {id: file}, dupes: [] }
function loadLessons() {
  global.window = global;
  global.document = global.document || { addEventListener() {}, querySelector() { return null; }, querySelectorAll() { return []; }, body: {}, documentElement: { dataset: {} } };
  if (!global.VIZ) vm.runInThisContext(fs.readFileSync(path.join(ROOT, '..', 'visualizers.js'), 'utf8'), { filename: 'visualizers.js' });
  vm.runInThisContext(fs.readFileSync(path.join(ROOT, 'lesson-kit.js'), 'utf8'), { filename: 'lesson-kit.js' });
  global.PLAN_LESSONS = {};
  const fileOf = {}, dupes = [];
  for (const f of lessonFiles()) {
    const before = new Set(Object.keys(global.PLAN_LESSONS));
    const prev = Object.assign({}, global.PLAN_LESSONS);
    vm.runInThisContext(fs.readFileSync(path.join(LESSON_DIR, f), 'utf8'), { filename: 'lessons/' + f });
    for (const id of Object.keys(global.PLAN_LESSONS)) {
      if (!before.has(id)) fileOf[id] = f;
      else if (prev[id] !== global.PLAN_LESSONS[id]) dupes.push(id + ' (' + fileOf[id] + ' + ' + f + ')');
    }
  }
  return { lessons: global.PLAN_LESSONS, fileOf, dupes };
}

function manifestText(items, fileOf) {
  const files = {};
  Object.keys(fileOf).sort().forEach(id => { files[id] = fileOf[id]; });
  const meta = {};
  // slug: LeetCode problem slug (dsa-visual ROADMAP se match karne ke liye — wahan already hai ya nahi)
  const slugOf = u => { const m = /leetcode\.com\/problems\/([^/]+)/.exec(u || ''); return m ? m[1] : undefined; };
  items.forEach(i => { meta[i.id] = Object.assign({ title: i.title, topic: i.topic, track: i.track }, i.diff ? { diff: i.diff } : {}, slugOf(i.url) ? { slug: slugOf(i.url) } : {}, i.track === 'th' ? { kind: i.kind } : {}); });
  return '// AUTO-GENERATED by planner/tools/build.js — haath se edit mat karo.\n' +
    '// files: kis item ka lesson kis file me · items: planner ke saare items (title / topic)\n' +
    'window.PLAN_MANIFEST = ' + JSON.stringify({ files, items: meta }, null, 0) + ';\n';
}

module.exports = { ROOT, LESSON_DIR, plannerItems, lessonFiles, loadLessons, manifestText };
